/**
 * Convert setup modifiers to safe values.
 */
export function normalizeSetupModifiers(
  modifiers:
    | RaceSetupModifiers
    | undefined,
): RaceSetupModifiers {
  return {
    launch:
      modifiers?.launch ?? 0,

    acceleration:
      modifiers?.acceleration ?? 0,

    topSpeed:
      modifiers?.topSpeed ?? 0,

    braking:
      modifiers?.braking ?? 0,

    handling:
      modifiers?.handling ?? 0,

    consistency:
      modifiers?.consistency ?? 0,

    reliability:
      modifiers?.reliability ?? 0,
  };
}

/**
 * Apply setup modifiers.
 */
export function applySetupModifiers(
  attributes: RacePerformance,
  modifiers:
    | RaceSetupModifiers
    | undefined,
): RacePerformance {
  const setup =
    normalizeSetupModifiers(
      modifiers,
    );

  return {
    ...attributes,

    launch:
      clampRaceStat(
        attributes.launch +
          (setup.launch ??
            0),
      ),

    acceleration:
      clampRaceStat(
        attributes.acceleration +
          (setup.acceleration ??
            0),
      ),

    topSpeed:
      clampRaceStat(
        attributes.topSpeed +
          (setup.topSpeed ??
            0),
      ),

    braking:
      clampRaceStat(
        attributes.braking +
          (setup.braking ??
            0),
      ),

    handling:
      clampRaceStat(
        attributes.handling +
          (setup.handling ??
            0),
      ),

    consistency:
      clampRaceStat(
        attributes.consistency +
          (setup.consistency ??
            0),
      ),

    reliability:
      clampRaceStat(
        attributes.reliability +
          (setup.reliability ??
            0),
      ),
  };
}

/**
 * Calculate base race performance.
 */
export function calculateRacePerformance(
  race:
    | RaceDefinition
    | undefined,
  motor:
    | MotorInstance
    | undefined,
  driver:
    | DriverDefinition
    | undefined,
  setupModifiers?:
    | RaceSetupModifiers,
  driverLevel = 1,
): RacePerformance {
  if (
    !race ||
    !motor ||
    !driver
  ) {
    return {
      launch: 0,
      acceleration: 0,
      topSpeed: 0,
      braking: 0,
      handling: 0,
      reaction: 0,
      consistency: 0,
      reliability: 0,
      overall: 0,
      weightedScore: 0,
      variance: 0,
      reliabilityPenalty: 0,
    };
  }

  const motorAttributes =
    getMotorRaceAttributes(
      motor,
    );

  const driverAttributes =
    getDriverRaceAttributes(
      driver,
    );

  const driverMultiplier =
    getDriverLevelMultiplier(
      driverLevel,
    );

  const raw: RacePerformance =
    {
      launch:
        combineStats(
          motorAttributes.launch,
          driverAttributes.launch,
          0.72,
          0.28,
          driverMultiplier,
        ),

      acceleration:
        motorAttributes.acceleration,

      topSpeed:
        motorAttributes.topSpeed,

      braking:
        combineStats(
          motorAttributes.braking,
          driverAttributes.control,
          0.78,
          0.22,
          driverMultiplier,
        ),

      handling:
        combineStats(
          motorAttributes.handling,
          driverAttributes.control,
          0.68,
          0.32,
          driverMultiplier,
        ),

      reaction:
        driverAttributes.reaction,

      consistency:
        driverAttributes.consistency,

      reliability:
        combineStats(
          motorAttributes.reliability,
          driverAttributes.focus,
          0.82,
          0.18,
          driverMultiplier,
        ),

      overall: 0,

      weightedScore: 0,

      variance: 0,

      reliabilityPenalty: 0,
    };

  const performance =
    applySetupModifiers(
      raw,
      setupModifiers,
    );

  const weightedScore =
    calculateRaceWeightedScore(
      race,
      performance,
    );

  const overall =
    Math.round(
      (
        performance.launch +
        performance.acceleration +
        performance.topSpeed +
        performance.braking +
        performance.handling +
        performance.reaction +
        performance.consistency +
        performance.reliability
      ) /
        8,
    );

  const reliabilityPenalty =
    calculateReliabilityPenalty(
      race,
      performance,
    );

  return {
    ...performance,

    overall,

    weightedScore,

    reliabilityPenalty,
  };
}

/**
 * Combine motor and driver contributions.
 */
export function combineStats(
  motorValue: number,
  driverValue: number,
  motorWeight: number,
  driverWeight: number,
  multiplier = 1,
): number {
  const result =
    (
      motorValue *
        motorWeight +
      driverValue *
        driverWeight
    ) *
    multiplier;

  return clampRaceStat(
    result,
  );
}

/**
 * Calculate weighted race score.
 */
export function calculateRaceWeightedScore(
  race:
    | RaceDefinition
    | undefined,
  performance:
    | RacePerformance
    | undefined,
): number {
  if (
    !race ||
    !performance
  ) {
    return 0;
  }

  const setup =
    race.setup;

  const weighted =
    performance.launch *
      setup.launchImportance +
    performance.acceleration *
      setup.accelerationImportance +
    performance.topSpeed *
      setup.topSpeedImportance +
    performance.braking *
      setup.brakingImportance +
    performance.handling *
      setup.handlingImportance +
    performance.reaction *
      setup.reactionImportance +
    performance.consistency *
      setup.consistencyImportance +
    performance.reliability *
      setup.reliabilityImportance;

  const weightTotal =
    setup.launchImportance +
    setup.accelerationImportance +
    setup.topSpeedImportance +
    setup.brakingImportance +
    setup.handlingImportance +
    setup.reactionImportance +
    setup.consistencyImportance +
    setup.reliabilityImportance;

  if (
    weightTotal <= 0
  ) {
    return 0;
  }

  return clampRaceStat(
    weighted /
      weightTotal,
  );
}

/**
 * Calculate reliability penalty.
 */
export function calculateReliabilityPenalty(
  race:
    | RaceDefinition
    | undefined,
  performance:
    | RacePerformance
    | undefined,
): number {
  if (
    !race ||
    !performance
  ) {
    return 0;
  }

  const pressure =
    race.conditions
      .reliabilityPressure;

  const reliability =
    performance.reliability;

  if (
    reliability >=
    pressure
  ) {
    return 0;
  }

  return clampRaceStat(
    (
      pressure -
      reliability
    ) *
      1.2,
  );
}

/**
 * Calculate mechanical risk percentage.
 */
export function calculateMechanicalRisk(
  race:
    | RaceDefinition
    | undefined,
  motor:
    | MotorInstance
    | undefined,
  performance?:
    | RacePerformance,
): number {
  if (
    !race ||
    !motor
  ) {
    return 100;
  }

  const stats =
    performance ??
    calculateRacePerformance(
      race,
      motor,
      undefined,
    );

  const reliability =
    calculateMotorRaceAttributes(
      motor,
    ).reliability;

  const conditionRisk =
    Math.max(
      0,
      (
        65 -
        motor.condition
      ) *
        0.65,
    );

  const pressureRisk =
    race.conditions
      .reliabilityPressure *
      0.8;

  const performanceRisk =
    Math.max(
      0,
      55 -
        stats.reliability,
    ) *
    0.55;

  const risk =
    conditionRisk +
    pressureRisk +
    performanceRisk;

  return clamp(
    Math.round(
      (
        risk +
        (
          100 -
          reliability
        ) *
          0.12
      ),
    ),
    0,
    100,
  );
}

