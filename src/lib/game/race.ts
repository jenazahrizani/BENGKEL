/**
 * Validate a race result.
 *
 * Useful before persisting it in GameState.
 */
export function validateRaceResult(
  result:
    | RaceResult
    | undefined,
): {
  valid: boolean;
  errors: string[];
} {
  const errors: string[] = [];

  if (!result) {
    return {
      valid: false,
      errors: [
        "Race result tidak tersedia.",
      ],
    };
  }

  if (
    !result.raceId
  ) {
    errors.push(
      "raceId kosong.",
    );
  }

  if (
    result.fieldSize <= 0
  ) {
    errors.push(
      "fieldSize harus lebih besar dari 0.",
    );
  }

  if (
    result.playerPosition <=
      0 ||
    result.playerPosition >
      result.fieldSize
  ) {
    errors.push(
      "playerPosition tidak valid.",
    );
  }

  if (
    result.playerFinished &&
    result.playerFinishTimeMs <=
      0
  ) {
    errors.push(
      "Finished player harus memiliki finish time.",
    );
  }

  if (
    result.motorWear < 0
  ) {
    errors.push(
      "motorWear tidak boleh negatif.",
    );
  }

  if (
    result.championshipPoints < 0
  ) {
    errors.push(
      "championshipPoints tidak boleh negatif.",
    );
  }

  const positions =
    result.standings.map(
      (entry) =>
        entry.position,
    );

  const uniquePositions =
    unique(
      positions,
    );

  if (
    uniquePositions.length !==
    positions.length
  ) {
    errors.push(
      "Standings memiliki posisi duplikat.",
    );
  }

  if (
    result.standings.length !==
    result.fieldSize
  ) {
    errors.push(
      "Jumlah standings tidak sama dengan fieldSize.",
    );
  }

  return {
    valid:
      errors.length === 0,

    errors,
  };
}
