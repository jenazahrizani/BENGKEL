/**
 * Validate race requirements.
 */
export function validateRaceRequirements(
  race:
    | RaceDefinition
    | undefined,
  context:
    | RacePlayerContext
    | undefined,
  motor:
    | MotorInstance
    | undefined,
  driver:
    | DriverDefinition
    | undefined,
): RaceEntryValidation {
  const errors:
    RaceEntryErrorCode[] = [];

  const messages:
    string[] = [];

  const warnings:
    string[] = [];

  if (!race) {
    return {
      valid: false,

      errors: [
        "RACE_NOT_FOUND",
      ],

      messages: [
        "Event race tidak ditemukan.",
      ],

      warnings: [],
    };
  }

  if (!context) {
    return {
      valid: false,

      errors: [
        "INVALID_ENTRY",
      ],

      messages: [
        "Player context tidak tersedia.",
      ],

      warnings: [],
    };
  }

  if (!motor) {
    errors.push(
      "MOTOR_NOT_FOUND",
    );

    messages.push(
      "Motor tidak ditemukan.",
    );
  }

  if (!driver) {
    errors.push(
      "DRIVER_NOT_FOUND",
    );

    messages.push(
      "Driver tidak ditemukan.",
    );
  }

  if (motor) {
    const motorDefinition =
      getMotorDefinition(
        motor,
      );

    if (!motorDefinition) {
      errors.push(
        "MOTOR_NOT_FOUND",
      );

      messages.push(
        "Definisi motor tidak ditemukan.",
      );
    } else if (
      motorDefinition.class !==
      race.class
    ) {
      errors.push(
        "WRONG_MOTOR_CLASS",
      );

      messages.push(
        `Motor harus berada di kelas ${race.class}.`,
      );
    }

    const readiness =
      getMotorRaceReadiness(
        motor,
      );

    if (!readiness.ready) {
      errors.push(
        "MOTOR_NOT_READY",
      );

      messages.push(
        ...readiness.issues,
      );
    }

    if (
      motor.condition <
      20
    ) {
      errors.push(
        "MOTOR_CONDITION_TOO_LOW",
      );

      messages.push(
        "Condition motor terlalu rendah.",
      );
    }

    if (
      motor.condition <
      45
    ) {
      warnings.push(
        "Condition motor rendah dan meningkatkan mechanical risk.",
      );
    }
  }

  if (driver) {
    /**
     * Driver class compatibility.
     *
     * UNDER_125 can drive UNDER_110 and UNDER_125.
     * OPEN only accepts OPEN.
     */
    if (
      !isDriverClassEligible(
        driver.class,
        race.class,
      )
    ) {
      errors.push(
        "DRIVER_CLASS_NOT_ELIGIBLE",
      );

      messages.push(
        `Driver ${driver.class} tidak memenuhi kelas ${race.class}.`,
      );
    }
  }

  /* Explicit race requirements */
  for (
    const requirement of
      race.requirements
  ) {
    switch (
      requirement.type
    ) {
      case "GARAGE_LEVEL": {
        const required =
          Number(
            requirement.value,
          );

        if (
          context.garageLevel <
          required
        ) {
          errors.push(
            "GARAGE_LEVEL_TOO_LOW",
          );

          messages.push(
            `Garage minimal level ${required}.`,
          );
        }

        break;
      }

      case "REPUTATION": {
        const required =
          Number(
            requirement.value,
          );

        if (
          context.reputation <
          required
        ) {
          errors.push(
            "REPUTATION_TOO_LOW",
          );

          messages.push(
            `Reputation minimal ${required}.`,
          );
        }

        break;
      }

      case "DRIVER_CLASS": {
        if (
          driver &&
          !isDriverClassEligible(
            driver.class,
            String(
              requirement.value,
            ) as DriverClass,
          )
        ) {
          errors.push(
            "DRIVER_CLASS_NOT_ELIGIBLE",
          );

          messages.push(
            "Kelas driver tidak memenuhi requirement.",
          );
        }

        break;
      }

      case "DRIVER_LEVEL": {
        /**
         * RaceEntry intentionally does not require a level,
         * but callers may pass it in future.
         *
         * The catalog currently does not define DriverInstance.
         * Therefore a direct level requirement is rejected unless
         * caller extends this engine with richer player-driver state.
         */
        warnings.push(
          "Driver level requirement memerlukan driver instance dari GameState.",
        );

        break;
      }

      case "TEAM_LEVEL": {
        const required =
          Number(
            requirement.value,
          );

        if (
          (context.teamLevel ??
            0) <
          required
        ) {
          errors.push(
            "TEAM_LEVEL_TOO_LOW",
          );

          messages.push(
            `Team minimal level ${required}.`,
          );
        }

        break;
      }

      case "LICENSE": {
        const license =
          String(
            requirement.value,
          );

        if (
          !context.licenses?.includes(
            license,
          )
        ) {
          errors.push(
            "LICENSE_REQUIRED",
          );

          messages.push(
            `Lisensi ${license} diperlukan.`,
          );
        }

        break;
      }

      case "CHAMPIONSHIP": {
        const championshipId =
          String(
            requirement.value,
          );

        if (
          !context.championships?.includes(
            championshipId,
          )
        ) {
          /**
           * For championship races, the championship ID usually
           * means the player must have entered / unlocked the series.
           */
          warnings.push(
            `Progress championship ${championshipId} harus diverifikasi oleh GameState.`,
          );
        }

        break;
      }

      case "MOTOR_CLASS": {
        if (
          motor &&
          getMotorRaceClass(
            motor,
          ) !==
            String(
              requirement.value,
            )
        ) {
          errors.push(
            "WRONG_MOTOR_CLASS",
          );

          messages.push(
            "Kelas motor tidak memenuhi requirement.",
          );
        }

        break;
      }

      case "MOTOR_CATEGORY":
      case "MOTOR_CONDITION":
      case "DRIVER_LEVEL":
      case "MOTOR_CLASS":
      case "PART": {
        /**
         * These can require richer GameState data.
         * Core class / condition is checked where possible.
         */
        if (
          requirement.type ===
          "MOTOR_CONDITION"
        ) {
          const required =
            Number(
              requirement.value,
            );

          if (
            (motor?.condition ??
              0) <
            required
          ) {
            errors.push(
              "MOTOR_CONDITION_TOO_LOW",
            );

            messages.push(
              `Condition motor minimal ${required}%.`,
            );
          }
        }

        break;
      }
    }
  }

  return {
    valid:
      errors.length === 0,

    errors: unique(
      errors,
    ),

    messages:
      unique(
        messages,
      ),

    warnings:
      unique(
        warnings,
      ),
  };
}

/**
 * Driver class compatibility.
 */
export function isDriverClassEligible(
  driverClass:
    | DriverClass
    | string,
  raceClass:
    | RaceClass
    | string,
): boolean {
  if (
    raceClass ===
    "OPEN"
  ) {
    return (
      driverClass ===
      "OPEN"
    );
  }

  if (
    raceClass ===
      "UNDER_110" ||
    raceClass ===
      "UNDER_125"
  ) {
    return (
      driverClass ===
        "UNDER_125" ||
      driverClass ===
        "UNDER_110"
    );
  }

  if (
    raceClass ===
    "UNDER_150"
  ) {
    return (
      driverClass ===
        "UNDER_125" ||
      driverClass ===
        "UNDER_150" ||
      driverClass ===
        "OPEN"
    );
  }

  return false;
}

/**
 * Remove duplicate array values.
 */
export function unique<T>(
  items: readonly T[],
): T[] {
  return [
    ...new Set(
      items,
    ),
  ];
}

