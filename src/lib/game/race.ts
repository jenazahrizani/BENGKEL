/**
 * Calculate motor wear after race.
 */
export function calculateMotorRaceWear(
  race:
    | RaceDefinition
    | undefined,
  motor:
    | MotorInstance
    | undefined,
  performance:
    | RacePerformance
    | undefined,
  dnf = false,
): number {
  if (
    !race ||
    !motor
  ) {
    return 0;
  }

  const pressure =
    race.conditions
      .reliabilityPressure;

  const reliability =
    performance?.reliability ??
    getMotorRaceAttributes(
      motor,
    ).reliability;

  const distanceFactor =
    Math.sqrt(
      race.distance.meters /
        201,
    );

  const reliabilityFactor =
    Math.max(
      0.5,
      1 +
        (
          60 -
          reliability
        ) /
          100,
    );

  const conditionFactor =
    motor.condition <
    50
      ? 1.25
      : 1;

  const dnfFactor =
    dnf
      ? 1.75
      : 1;

  const wear =
    MOTOR_WEAR_BASE *
    distanceFactor *
    (
      1 +
      pressure /
        100
    ) *
    reliabilityFactor *
    conditionFactor *
    dnfFactor;

  return Number(
    wear.toFixed(2),
  );
}

/**
 * Calculate installed-part wear.
 *
 * Keys match motor.ts installedParts categories.
 */
export function calculateInstalledPartWear(
  motor:
    | MotorInstance
    | undefined,
  race:
    | RaceDefinition
    | undefined,
  performance:
    | RacePerformance
    | undefined,
  dnf = false,
): Record<string, number> {
  if (
    !motor ||
    !race
  ) {
    return {};
  }

  const result:
    Record<string, number> =
      {};

  const base =
    calculateMotorRaceWear(
      race,
      motor,
      performance,
      dnf,
    );

  for (
    const category of Object.keys(
      motor.installedParts,
    )
  ) {
    if (
      !motor.installedParts[
        category
      ]
    ) {
      continue;
    }

    /**
     * Brakes / tires / clutch / drivetrain receive
     * more wear in race use.
     */
    let multiplier = 0.55;

    if (
      category ===
      "BRAKE"
    ) {
      multiplier = 0.85;
    } else if (
      category ===
      "TIRE"
    ) {
      multiplier = 0.95;
    } else if (
      category ===
      "CLUTCH"
    ) {
      multiplier = 0.9;
    } else if (
      category ===
      "TRANSMISSION"
    ) {
      multiplier = 0.75;
    } else if (
      category ===
      "ENGINE"
    ) {
      multiplier = 1;
    } else if (
      category ===
      "EXHAUST"
    ) {
      multiplier = 0.5;
    }

    if (
      dnf
    ) {
      multiplier *= 1.35;
    }

    result[
      category
    ] = Number(
      (
        base *
        multiplier *
        (
          PART_WEAR_BASE /
          MOTOR_WEAR_BASE
        )
      ).toFixed(2),
    );
  }

  return result;
}

