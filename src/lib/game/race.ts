/* DNF / MECHANICAL FAILURE                                                   */
/* -------------------------------------------------------------------------- */

/**
 * Calculate chance of DNF.
 *
 * Result is 0-1.
 */
export function calculateDnfChance(
  race:
    | RaceDefinition
    | undefined,
  motor:
    | MotorInstance
    | undefined,
  performance:
    | RacePerformance
    | undefined,
  mechanicalRisk?: number,
): number {
  if (
    !race ||
    !motor
  ) {
    return 1;
  }

  const risk =
    mechanicalRisk ??
    calculateMechanicalRisk(
      race,
      motor,
      performance,
    );

  /**
   * Baseline:
   * - healthy motor, low-pressure event -> ~1%
   * - high risk -> substantially higher
   */
  let chance =
    DNF_BASE_CHANCE +
    risk / 450;

  if (
    race.conditions
      .reliabilityPressure >=
    20
  ) {
    chance += 0.04;
  }

  if (
    motor.condition <
    40
  ) {
    chance += 0.06;
  }

  if (
    performance &&
    performance.reliability <
    40
  ) {
    chance += 0.05;
  }

  return clamp(
    chance,
    0,
    0.85,
  );
}

/**
 * Pick DNF reason.
 */
export function getDnfReason(
  race:
    | RaceDefinition
    | undefined,
  performance:
    | RacePerformance
    | undefined,
  motor:
    | MotorInstance
    | undefined,
  random: RandomFn,
): RaceDnfReason {
  if (!race) {
    return "NO_FINISH";
  }

  const reliability =
    performance?.reliability ??
    0;

  const condition =
    motor?.condition ??
    0;

  const roll =
    safeRandom(
      random,
    );

  if (
    condition <
    20
  ) {
    return "ENGINE_FAILURE";
  }

  if (
    race.conditions
      .reliabilityPressure >=
      22 &&
    reliability <
    45
  ) {
    return "MECHANICAL_FAILURE";
  }

  if (
    roll <
    0.25
  ) {
    return "CRASH";
  }

  return "MECHANICAL_FAILURE";
}

