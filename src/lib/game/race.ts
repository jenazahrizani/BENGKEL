/**
 * Create a seeded pseudo-random generator.
 *
 * This is intentionally tiny and deterministic for testing.
 */
export function createSeededRandom(
  seed: number,
): RandomFn {
  let value =
    Math.floor(seed) >>> 0;

  return () => {
    value =
      (value * 1664525 +
        1013904223) >>>
      0;

    return (
      value /
      4_294_967_296
    );
  };
}

/**
 * Normalize random value.
 */
export function safeRandom(
  random: RandomFn,
): number {
  const value =
    random();

  if (
    !Number.isFinite(
      value,
    )
  ) {
    return 0.5;
  }

  return Math.min(
    0.999999,
    Math.max(0, value),
  );
}

/**
 * Pick random item.
 */
export function randomItem<T>(
  items: readonly T[],
  random: RandomFn,
): T | undefined {
  if (
    items.length === 0
  ) {
    return undefined;
  }

  const index =
    Math.floor(
      safeRandom(random) *
        items.length,
    );

  return items[index];
}

