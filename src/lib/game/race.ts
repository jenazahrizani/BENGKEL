/**
 * Optional driver-level scaling.
 *
 * Higher level gives a very small performance bump.
 */
export function getDriverLevelMultiplier(
  level = 1,
): number {
  const safeLevel =
    Math.max(
      1,
      Math.floor(
        level,
      ),
    );

  return (
    1 +
    Math.min(
      0.12,
      (safeLevel - 1) *
        0.02,
    )
  );
}

