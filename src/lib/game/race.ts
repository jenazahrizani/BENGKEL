/**
 * Calculate launch advantage.
 */
export function calculateLaunchAdvantage(
  race:
    | RaceDefinition
    | undefined,
  motor:
    | MotorInstance
    | undefined,
  driver:
    | DriverDefinition
    | undefined,
): number {
  if (
    !race ||
    !motor ||
    !driver
  ) {
    return 0;
  }

  const performance =
    calculateRacePerformance(
      race,
      motor,
      driver,
    );

  return clampRaceStat(
    (
      performance.launch *
        race.setup.launchImportance +
      performance.reaction *
        race.setup.reactionImportance
    ) /
      Math.max(
        1,
        race.setup.launchImportance +
          race.setup.reactionImportance,
      ),
  );
}

/**
 * Calculate consistency advantage.
 */
export function calculateConsistencyAdvantage(
  race:
    | RaceDefinition
    | undefined,
  motor:
    | MotorInstance
    | undefined,
  driver:
    | DriverDefinition
    | undefined,
): number {
  if (
    !race ||
    !motor ||
    !driver
  ) {
    return 0;
  }

  const performance =
    calculateRacePerformance(
      race,
      motor,
      driver,
    );

  return clampRaceStat(
    (
      performance.consistency *
        race.setup.consistencyImportance +
      performance.reliability *
        race.setup.reliabilityImportance
    ) /
      Math.max(
        1,
        race.setup.consistencyImportance +
          race.setup.reliabilityImportance,
      ),
  );
}

/**
 * Return primary race factor.
 */
export function getRacePrimaryFactor(
  race:
    | RaceDefinition
    | undefined,
): {
  factor:
    | "launch"
    | "acceleration"
    | "topSpeed"
    | "braking"
    | "handling"
    | "reaction"
    | "consistency"
    | "reliability";

  weight: number;
} {
  if (!race) {
    return {
      factor:
        "consistency",

      weight: 0,
    };
  }

  const candidates = [
    [
      "launch",
      race.setup.launchImportance,
    ],

    [
      "acceleration",
      race.setup.accelerationImportance,
    ],

    [
      "topSpeed",
      race.setup.topSpeedImportance,
    ],

    [
      "braking",
      race.setup.brakingImportance,
    ],

    [
      "handling",
      race.setup.handlingImportance,
    ],

    [
      "reaction",
      race.setup.reactionImportance,
    ],

    [
      "consistency",
      race.setup.consistencyImportance,
    ],

    [
      "reliability",
      race.setup.reliabilityImportance,
    ],
  ] as const;

  return candidates.reduce(
    (
      best,
      current,
    ) =>
      current[1] >
      best[1]
        ? current
        : best,
  );
}

/**
 * Return whether a race has meaningful mechanical risk.
 */
export function isHighRiskRace(
  race:
    | RaceDefinition
    | undefined,
): boolean {
  if (!race) {
    return false;
  }

  return (
    race.conditions
      .reliabilityPressure >=
    HIGH_RISK_THRESHOLD / 3
  );
}

