/**
 * Generate opponent motor condition.
 */
export function generateOpponentCondition(
  random: RandomFn,
): number {
  const roll =
    safeRandom(random);

  /**
   * Most opponents should be in usable condition.
   */
  if (
    roll < 0.1
  ) {
    return 55 +
      Math.round(
        safeRandom(
          random,
        ) * 15,
      );
  }

  return 72 +
    Math.round(
      safeRandom(
        random,
      ) * 26,
    );
}

/**
 * Generate opponent driver level based on event.
 */
export function generateOpponentDriverLevel(
  race:
    | RaceDefinition
    | undefined,
  random: RandomFn,
): number {
  if (!race) {
    return 1;
  }

  let base = 1;

  switch (
    race.difficulty
  ) {
    case "BEGINNER":
      base = 1;
      break;

    case "NOVICE":
      base = 2;
      break;

    case "INTERMEDIATE":
      base = 3;
      break;

    case "HARD":
      base = 4;
      break;

    case "PRO":
      base = 5;
      break;

    case "ELITE":
      base = 7;
      break;
  }

  const variance =
    Math.floor(
      safeRandom(
        random,
      ) * 3,
    ) - 1;

  return Math.max(
    1,
    base + variance,
  );
}

/**
 * Generate opponent setup variation.
 */
export function generateOpponentSetup(
  race:
    | RaceDefinition
    | undefined,
  random: RandomFn,
): RaceSetupModifiers {
  if (!race) {
    return {};
  }

  const variation =
    () =>
      Math.round(
        (
          safeRandom(
            random,
          ) *
            2 -
          1
        ) *
          5,
      );

  return {
    launch:
      variation(),

    acceleration:
      variation(),

    topSpeed:
      variation(),

    braking:
      variation(),

    handling:
      variation(),

    consistency:
      variation(),

    reliability:
      variation(),
  };
}

