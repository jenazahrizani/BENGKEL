/**
 * Simulate a complete race.
 */
export function simulateRace(
  entry:
    | RaceEntry
    | undefined,
  context:
    | RacePlayerContext
    | undefined,
  options: RaceSimulationOptions = {},
): RaceResult | undefined {
  if (
    !entry ||
    !context
  ) {
    return undefined;
  }

  const race =
    getRaceById(
      entry.raceId,
    );

  if (!race) {
    return undefined;
  }

  const driver =
    getDriverById(
      entry.driverId,
    );

  if (!driver) {
    return undefined;
  }

  const validation =
    validateRaceRequirements(
      race,
      context,
      entry.motor,
      driver,
    );

  if (
    !validation.valid
  ) {
    return undefined;
  }

  const random =
    options.random ??
    (
      options.seed !==
      undefined
        ? createSeededRandom(
            options.seed,
          )
        : Math.random
    );

  const difficultyMultiplier =
    options.difficultyMultiplier ??
    1;

  const playerDriver =
    createPlayerSimulationDriver(
      race,
      {
        ...entry,

        setupModifiers:
          options.playerSetupModifiers ??
          entry.setupModifiers,
      },
      random,
    );

  if (
    !playerDriver
  ) {
    return undefined;
  }

  playerDriver.finalPerformance =
    recomputeWeightedPerformance(
      race,
      playerDriver.finalPerformance,
    );

  const mechanicalRisk =
    calculateMechanicalRisk(
      race,
      entry.motor,
      playerDriver.finalPerformance,
    );

  const playerDnfChance =
    calculateDnfChance(
      race,
      entry.motor,
      playerDriver.finalPerformance,
      mechanicalRisk,
    );

  if (
    safeRandom(
      random,
    ) <
    playerDnfChance
  ) {
    playerDriver.dnf =
      true;

    playerDriver.dnfReason =
      getDnfReason(
        race,
        playerDriver.finalPerformance,
        entry.motor,
        random,
      );

    playerDriver.finishTimeMs =
      MAX_FINISH_TIME_MS;
  } else {
    playerDriver.finishTimeMs =
      calculateFinishTimeMs(
        race,
        playerDriver.finalPerformance,
        random,
        difficultyMultiplier,
      );
  }

  const opponentDefinitions =
    options.opponents ??
    generateDefaultOpponents(
      race,
      getRequestedOpponentCount(
        race,
        options.opponentCount,
      ),
      random,
    );

  const opponents:
    RaceSimulationDriver[] =
      [];

  for (
    const opponent of
      opponentDefinitions
  ) {
    const simulated =
      createOpponentSimulationDriver(
        race,
        opponent,
        random,
      );

    if (!simulated) {
      continue;
    }

    simulated.finalPerformance =
      recomputeWeightedPerformance(
        race,
        simulated.finalPerformance,
      );

    const opponentMotor =
      simulated.motor;

    const opponentRisk =
      calculateMechanicalRisk(
        race,
        opponentMotor,
        simulated.finalPerformance,
      );

    const opponentDnfChance =
      calculateDnfChance(
        race,
        opponentMotor,
        simulated.finalPerformance,
        opponentRisk,
      );

    if (
      safeRandom(
        random,
      ) <
      opponentDnfChance
    ) {
      simulated.dnf =
        true;

      simulated.dnfReason =
        getDnfReason(
          race,
          simulated.finalPerformance,
          opponentMotor,
          random,
        );

      simulated.finishTimeMs =
        MAX_FINISH_TIME_MS;
    } else {
      simulated.finishTimeMs =
        calculateFinishTimeMs(
          race,
          simulated.finalPerformance,
          random,
          difficultyMultiplier,
        );
    }

    opponents.push(
      simulated,
    );
  }

  const field = [
    playerDriver,
    ...opponents,
  ];

  assignRacePositions(
    field,
  );

  /**
   * If we accidentally generated fewer opponents than minimum field,
   * the simulation still remains valid. Field is never fabricated
   * after the fact.
   */
  const playerPosition =
    playerDriver.position;

  const playerFinished =
    !playerDriver.dnf;

  const rewards =
    playerFinished
      ? calculateRaceRewards(
          race,
          playerPosition,
        )
      : calculateDidNotFinishRewards(
          race,
        );

  const motorWear =
    calculateMotorRaceWear(
      race,
      entry.motor,
      playerDriver.finalPerformance,
      playerDriver.dnf,
    );

  const partWear =
    calculateInstalledPartWear(
      entry.motor,
      race,
      playerDriver.finalPerformance,
      playerDriver.dnf,
    );

  const championshipPoints =
    playerFinished
      ? calculateChampionshipPoints(
          race,
          playerPosition,
        )
      : 0;

  return {
    raceId:
      race.id,

    simulatedAt:
      Date.now(),

    playerPosition,

    playerFinished,

    playerFinishTimeMs:
      playerDriver.finishTimeMs,

    playerFinishTime:
      playerDriver.dnf
        ? "DNF"
        : formatRaceTime(
            playerDriver.finishTimeMs,
          ),

    fieldSize:
      field.length,

    standings:
      field,

    rewards,

    motorWear,

    partWear,

    championshipPoints,

    performanceScore:
      playerDriver.finalPerformance
        .weightedScore,

    mechanicalRisk,

    seed:
      options.seed,
  };
}

/**
 * Determine opponent count.
 */
export function getRequestedOpponentCount(
  race:
    | RaceDefinition
    | undefined,
  requested?: number,
): number {
  if (!race) {
    return 0;
  }

  if (
    requested !==
    undefined
  ) {
    return clamp(
      Math.floor(
        requested,
      ),
      1,
      race.field.maximumDrivers -
        1,
    );
  }

  return clamp(
    DEFAULT_OPPONENT_COUNT,
    race.field.minimumDrivers -
      1,
    race.field.maximumDrivers -
      1,
  );
}

/**
 * Assign positions by finish time.
 *
 * DNF always ranks behind finishers.
 */
export function assignRacePositions(
  field:
    | RaceSimulationDriver[]
    | undefined,
): void {
  if (!field) {
    return;
  }

  field.sort(
    (
      a,
      b,
    ) => {
      if (
        a.dnf &&
        !b.dnf
      ) {
        return 1;
      }

      if (
        !a.dnf &&
        b.dnf
      ) {
        return -1;
      }

      return (
        a.finishTimeMs -
        b.finishTimeMs
      );
    },
  );

  for (
    let i = 0;
    i < field.length;
    i += 1
  ) {
    field[i].position =
      i + 1;
  }
}

/**
 * Rewards for DNF.
 *
 * Direct event participation rewards are still granted,
 * but no finishing prize or championship points.
 */
export function calculateDidNotFinishRewards(
  race:
    | RaceDefinition
    | undefined,
): RaceResultReward[] {
  if (!race) {
    return [];
  }

  return race.rewards.filter(
    (reward) =>
      reward.type !==
      "CHAMPIONSHIP_POINTS",
  ).map(
    (reward) => ({
      type:
        reward.type,
      amount:
        reward.amount,
    }),
  );
}

