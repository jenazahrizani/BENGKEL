/**
 * Calculate nominal time from distance.
 */
export function calculateBaseRaceTimeMs(
  race:
    | RaceDefinition
    | undefined,
): number {
  if (!race) {
    return 0;
  }

  const bucket =
    getRaceDistanceBucket(
      race.distance.meters,
    );

  const base =
    BASE_TIME_MS_BY_DISTANCE[
      bucket
    ];

  /**
   * Scale base time with actual distance.
   *
   * This avoids 201m and 1,201m having similar times.
   */
  const distanceRatio =
    Math.sqrt(
      race.distance.meters /
        (
          bucket === "SHORT"
            ? 201
            : bucket ===
                "MEDIUM"
              ? 402
              : 1_201
        ),
    );

  return Math.round(
    base *
      distanceRatio,
  );
}

/**
 * Convert race score into final time.
 */
export function calculateFinishTimeMs(
  race:
    | RaceDefinition
    | undefined,
  performance:
    | RacePerformance
    | undefined,
  random: RandomFn,
  difficultyMultiplier = 1,
): number {
  if (
    !race ||
    !performance
  ) {
    return MAX_FINISH_TIME_MS;
  }

  const baseTime =
    calculateBaseRaceTimeMs(
      race,
    );

  /**
   * A higher performance score means faster time.
   *
   * Score 0   => slow
   * Score 50  => neutral
   * Score 100 => fast
   */
  const normalized =
    clamp(
      performance.weightedScore,
      0,
      100,
    ) /
    100;

  const performanceFactor =
    1 -
    (
      normalized -
      0.5
    ) *
      PERFORMANCE_TIME_FACTOR;

  const variance =
    (
      safeRandom(random) *
        2 -
      1
    ) *
    MAX_VARIANCE_PERCENT;

  let result =
    baseTime *
    performanceFactor *
    (
      1 +
      variance
    );

  /**
   * Reliability failure adds time before DNF is decided.
   */
  if (
    performance.reliabilityPenalty >
    0
  ) {
    result *=
      1 +
      performance.reliabilityPenalty /
        450;
  }

  result *=
    Math.max(
      0.8,
      Math.min(
        1.3,
        difficultyMultiplier,
      ),
    );

  return Math.round(
    clamp(
      result,
      MIN_FINISH_TIME_MS,
      MAX_FINISH_TIME_MS,
    ),
  );
}

