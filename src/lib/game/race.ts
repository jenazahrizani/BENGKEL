/**
 * Read driver stat safely.
 *
 * Kept defensive so race engine remains compatible
 * with catalog versions that add/remove optional stats later.
 */
export function getDriverStat(
  driver:
    | DriverDefinition
    | undefined,
  key:
    | "reaction"
    | "launch"
    | "shifting"
    | "consistency"
    | "control"
    | "focus"
    | "aggression",
): number {
  if (!driver) {
    return 0;
  }

  const value =
    driver.stats?.[key];

  return clampRaceStat(
    typeof value ===
      "number"
      ? value
      : 0,
  );
}

